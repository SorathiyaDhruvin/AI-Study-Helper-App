@Composable
fun AuthAlertDialog(
    onDismissRequest: () -> Unit,
    title: String,
    text: String,
    confirmButtonText: String = "OK",
    onConfirm: () -> Unit = onDismissRequest,
    dismissButtonText: String? = null,
    onDismiss: (() -> Unit)? = null
) {
    AlertDialog(
        onDismissRequest = onDismissRequest,
        shape = RoundedCornerShape(24.dp),
        containerColor = CardDark,
        title = {
            Text(title, color = TextPrimary, fontSize = 20.sp, fontWeight = FontWeight.Bold)
        },
        text = {
            Text(text, color = TextSecondary, fontSize = 16.sp)
        },
        confirmButton = {
            TextButton(onClick = onConfirm) {
                Text(confirmButtonText, color = GradientStart, fontWeight = FontWeight.Bold)
            }
        },
        dismissButton = {
            if (dismissButtonText != null && onDismiss != null) {
                TextButton(onClick = onDismiss) {
                    Text(dismissButtonText, color = TextSecondary)
                }
            }
        }
    )
}

